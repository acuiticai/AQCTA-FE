const locales = [
  { file: "en.json", creditNotes: creditNotesEn, debitNotes: debitNotesEn },
  { file: "id.json", creditNotes: creditNotesId, debitNotes: debitNotesId },
  { file: "ar.json", creditNotes: creditNotesAr, debitNotes: debitNotesAr },
];

const translationDir = path.join(__dirname, "..", "src", "utils", "translation");

for (const locale of locales) {
  const filePath = path.join(translationDir, locale.file);
  const data = JSON.parse(fs.readFileSync(filePath, "utf8"));
  if (!data.accounts) {
    throw new Error("Missing accounts namespace in " + locale.file);
  }
  data.accounts.creditNotes = locale.creditNotes;
  data.accounts.debitNotes = locale.debitNotes;
  fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + "\n", "utf8");
  console.log("Updated " + locale.file);
  console.log(
    "  sample: accounts.creditNotes.title = " + JSON.stringify(locale.creditNotes.title)
  );
  console.log(
    "  sample: accounts.debitNotes.title = " + JSON.stringify(locale.debitNotes.title)
  );
}

