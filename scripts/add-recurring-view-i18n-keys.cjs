const translationDir = path.join(__dirname, "..", "src", "utils", "translation");

for (const lang of ["en", "ar", "id"]) {
  const filePath = path.join(translationDir, `${lang}.json`);
  const data = JSON.parse(fs.readFileSync(filePath, "utf8"));
  const visible = data.accounts.recurringInvoices.visible;
  let added = 0;
  let skipped = 0;

  for (const [sourceText, translation] of Object.entries(newKeys[lang])) {
    const key = toVisibleKey(sourceText);
    if (visible[key] !== undefined) {
      skipped += 1;
      continue;
    }
    visible[key] = translation;
    added += 1;
  }

  fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + "\n", "utf8");
  console.log(`${lang}.json: added ${added}, skipped ${skipped} (already exist)`);
}

console.log("Done.");
