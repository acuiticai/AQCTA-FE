const Base_URL = import.meta.env.VITE_APP_API_BASE_URL;

const DocumentGenerator = ({
  open,
  onClose,
  uploadSign,
  customer_signature,
  proformaInvoice,
  onUpload,
  templateId,
  contractId,
  adminInfo,
  business_id,
  onSuccess,
  isAdvance,
  advanceAmount,
  autoGeneratePDF = false,
}) => {
  const [isGenerating, setIsGenerating] = useState(false);
  const [isLoading, setIsLoading] = useState(true);
  const [contractDetails, setContractDetails] = useState(null);
  const [businessDetails, setBusinessDetails] = useState(null);
  const [templateData, setTemplateData] = useState(null);
  const [renderedHtml, setRenderedHtml] = useState("");
  const [signatureFileURL, setSignatureFileURL] = useState("");
  const [BuyerAddress, setBuyerAddress] = useState("");
  const [isUploadingSigned, setIsUploadingSigned] = useState(false);
  const [isSuccessDialogOpen, setIsSuccessDialogOpen] = useState(false);
  const [successDialogText, setSuccessDialogText] = useState("");
  const [showPleaseWait, setShowPleaseWait] = useState(false);
  const [rejectOpen, setRejectOpen] = useState(false);
  const [amendOpen, setAmendOpen] = useState(false);
  const [rejectReason, setRejectReason] = useState("");
  const [amendComment, setAmendComment] = useState("");
  const [isRejecting, setIsRejecting] = useState(false);
  const [isRequestingAmendment, setIsRequestingAmendment] = useState(false);
  const [showEmailConfirmation, setShowEmailConfirmation] = useState(false);

  const handleSuccessOk = () => {
    setIsSuccessDialogOpen(false);
    if (uploadSign) {
      window.close();
    } else {
      onClose();
    }
  };

  console.log("contractId", contractId);
  console.log("templateId", templateId);
  console.log("template data", templateData);

  const fileInputRef = useRef(null);

  // Initial documents (left pane)
  const [initialDocuments, setInitialDocuments] = useState([]);
  const [fetchingInitialDocs, setFetchingInitialDocs] = useState(false);
  const [activeTab, setActiveTab] = useState(0);
  const [selectedInitialDoc, setSelectedInitialDoc] = useState(null);

  // Fetch contract and template data when dialog opens
  useEffect(() => {
    if (open && contractId && templateId) {
      fetchData();
      fetchInitialDocuments();
    }
  }, [open, contractId, templateId]);

  const fetchInitialDocuments = async () => {
    if (!contractId) return;
    try {
      setFetchingInitialDocs(true);
      const contractRes = await axios.get(
        `${Base_URL}/sales-contracts/${contractId}`
      );
      const contract = contractRes?.data;
      let docs = Array.isArray(contract?.initialDocuments)
        ? contract.initialDocuments
        : [];
      if ((!docs || docs.length === 0) && contract?.contractNo) {
        try {
          const filesRes = await axios.get(
            `${Base_URL}/documents/get_all_by_sales/${contract.contractNo}`
          );
          const files = filesRes?.data;
          if (Array.isArray(files)) {
            docs = files.map((f) => ({
              name: f.name,
              url: f.url,
              type: f.type,
              size: f.size || 0,
              uploadedAt: f.uploadDate || new Date().toISOString(),
            }));
          }
        } catch (e) {
          // ignore fallback failure
        }
      }
      setInitialDocuments(docs || []);
      setSelectedInitialDoc(docs && docs.length ? docs[0] : null);
    } catch (e) {
      // ignore
    } finally {
      setFetchingInitialDocs(false);
    }
  };

  // Auto-generate PDF only once per dialog open with autoGeneratePDF flag
  const hasAutoGeneratedRef = useRef(false);

  useEffect(() => {
    if (!open) {
      hasAutoGeneratedRef.current = false;
      return;
    }
    if (
      open &&
      autoGeneratePDF &&
      customer_signature &&
      !isLoading &&
      !isGenerating &&
      !hasAutoGeneratedRef.current
    ) {
      hasAutoGeneratedRef.current = true;
      setShowPleaseWait(true); // Show please wait popup
      const timer = setTimeout(() => {
        generatePDF();
      }, 1500);

      return () => clearTimeout(timer);
    }
  }, [open, autoGeneratePDF, customer_signature, isLoading, isGenerating]);

  const fetchData = async () => {
    setIsLoading(true);
    try {
      // Fetch contract details
      const contractResponse = await axios.get(
        `${Base_URL}/sales-contracts/${contractId}`
      );
      setContractDetails(contractResponse.data);
      console.log("contractResponse.data", contractResponse.data);

      // Fetch template details
      console.log("business_id", business_id);
      const businessDataRes = await axios.get(
        `${Base_URL}/business/${business_id}`
      );
      console.log("business Data Res", businessDataRes.data.data);
      setBusinessDetails(businessDataRes.data.data);

      const templateResponse = await axios.get(
        `${Base_URL}/document-templates/${templateId.split(":")[0]}`
      );
      setTemplateData(templateResponse.data);

      // Fetch admin signature
      if (adminInfo?.id) {
        const profileResponse = await axios.get(
          `${Base_URL}/admin/profile/${adminInfo?.id}`
        );
        if (profileResponse.data.signature) {
          setSignatureFileURL(profileResponse.data.signature);
        }
      }
      const BuyerResponse = await axios.get(
        `${Base_URL}/customers/address/${contractResponse.data.basicInfo.customer_id}`
      );

      // Once we have both contract and template data, render the HTML
      if (contractResponse.data && templateResponse.data) {
        console.log(
          "businessDataRes.data.data?.image",
          businessDataRes.data.data?.image
        );
        const businessLogo = businessDataRes.data.data?.image;
        const businessName = businessDataRes.data.data?.name || "";
        contractResponse.data.sellerName = businessName;
        contractResponse.data.businessLogo = businessLogo;
        contractResponse.data.businessName = businessName;
        contractResponse.data.supplierSign =
          contractResponse?.data?.approver_signature;
        contractResponse.data.BuyerSign = contractResponse.data.signature || "";

        let accountTypeName = "";
        if (contractResponse.data?.Account_Info?.accountType) {
          try {
            const accountTypeRes = await axios.get(
              `${Base_URL}/bank-account-types/${contractResponse.data.Account_Info.accountType}`
            );
            accountTypeName = accountTypeRes.data?.name || "";

            console.log("accountTypeName", accountTypeRes.data);
          } catch (err) {
            console.log("Failed to fetch account type name:", err);
          }
        }

        const html = renderTemplateWithContractData(
          templateResponse?.data?.data?.htmlContent,
          contractResponse.data,
          businessDataRes.data.data,
          accountTypeName,
          BuyerResponse?.data
        );
        setRenderedHtml(html);
      }
    } catch (error) {
      console.error("Error fetching data:", error);
      notifyError("Failed to load template or contract data");
    } finally {
      setIsLoading(false);
    }
  };

  // Update the renderTemplateWithContractData function to properly handle HTML content
  const renderTemplateWithContractData = useCallback(
    (
      templateContent,
      contractData,
      Business,
      accountTypeName,
      BuyerAddress
    ) => {
      if (!templateContent) {
        return "<!DOCTYPE html><html><head><title>Contract</title></head><body><h1>Error</h1><p>Template content is missing</p></body></html>";
      }

      if (!contractData) {
        return "<!DOCTYPE html><html><head><title>Contract</title></head><body><h1>Error</h1><p>Contract data is missing</p></body></html>";
      }
      console.log("contractData", contractData);
      const businessLogo = contractData?.businessLogo;
      const businessName = contractData?.businessName || "";
      const supplierSign = contractData?.supplierSign;
      const buyerSign = contractData?.customer_signature || "";
      console.log("businessLogo businessLogo", businessLogo);

      function convertTotalInWords(amount) {
        const a = [
          "",
          "One",
          "Two",
          "Three",
          "Four",
          "Five",
          "Six",
          "Seven",
          "Eight",
          "Nine",
          "Ten",
          "Eleven",
          "Twelve",
          "Thirteen",
          "Fourteen",
          "Fifteen",
          "Sixteen",
          "Seventeen",
          "Eighteen",
          "Nineteen",
        ];
        const b = [
          "",
          "",
          "Twenty",
          "Thirty",
          "Forty",
          "Fifty",
          "Sixty",
          "Seventy",
          "Eighty",
          "Ninety",
        ];

        const num = parseFloat(amount);
        if (isNaN(num)) return "Invalid amount";

        if (num === 0) return "Zero";

        function toWords(n) {
          if (n < 20) return a[n];
          if (n < 100)
            return b[Math.floor(n / 10)] + (n % 10 ? " " + a[n % 10] : "");
          if (n < 1000)
            return (
              a[Math.floor(n / 100)] +
              " Hundred" +
              (n % 100 ? " and " + toWords(n % 100) : "")
            );
          if (n < 100000)
            return (
              toWords(Math.floor(n / 1000)) +
              " Thousand" +
              (n % 1000 ? " " + toWords(n % 1000) : "")
            );
          if (n < 10000000)
            return (
              toWords(Math.floor(n / 100000)) +
              " Lakh" +
              (n % 100000 ? " " + toWords(n % 100000) : "")
            );
          return (
            toWords(Math.floor(n / 10000000)) +
            " Crore" +
            (n % 10000000 ? " " + toWords(n % 10000000) : "")
          );
        }

        const [rupees, paise] = num.toFixed(2).split(".");

        let words = `${toWords(parseInt(rupees))} Rupees`;
        if (parseInt(paise) > 0) {
          words += ` and ${toWords(parseInt(paise))} Paise`;
        }

        return words + " Only";
      }

      // Create data object from contract data
      const data = {
        contract: {
          ref: contractData?.basicInfo?.ref || "",
          contractNo: contractData.contractNo || "",
          date: formatDate(contractData?.basicInfo?.contractCreationDate) || "",
          buyerName: contractData.basicInfo?.buyerCompanyName || "",
          buyerAddress: BuyerAddress,
          buyerAddress2:
            contractData.basicInfo?.customerAddress
              ?.split("\n")
              .slice(1)
              .join(", ") || "",
          grade:
            contractData.productInfo?.[0]?.title +
              " " +
              contractData.productInfo?.[0]?.grade || "",
          goods_description: contractData.productInfo?.[0]?.title || "",
          totalInWords: convertTotalInWords(
            isAdvance
              ? advanceAmount
              : contractData.productInfo?.[0]?.totalValue || ""
          ),
          quantity: isAdvance
            ? 1
            : contractData.productInfo?.[0]?.quantityMTS *
                contractData.productInfo?.[0]?.quantityFCL +
                "MTS (At " +
                contractData.productInfo?.[0]?.quantityMTS +
                "MTS x " +
                contractData.productInfo?.[0]?.containerType +
                " of " +
                contractData.productInfo?.[0]?.quantityFCL +
                " FCL)" || "",
          price: isAdvance
            ? formatAmount(advanceAmount)
            : formatAmount(contractData.productInfo?.[0]?.price) || "",
          totalValue: isAdvance
            ? formatAmount(advanceAmount)
            : formatAmount(contractData.productInfo?.[0]?.totalValue) || "",
          shippingTerms: contractData.productInfo?.[0]?.shippingTerms || "",
          packing: contractData.productInfo?.[0]?.packing || "",
          etdPort: contractData.basicInfo?.etdPort || "",
          ETD_Port: formatDate(contractData.basicInfo?.ETD_Port, true) || "",
          origin_country: contractData.basicInfo?.origin_country || "",
          port_of_loading: contractData.basicInfo?.port_of_loading || "",
          port_of_discharge: contractData.basicInfo?.port_of_discharge || "",
          payment: contractData.productInfo?.[0]?.paymentTerms || "",
          terms: contractData.productInfo?.[0]?.shippingTerms || "",
          Account_Info: {
            accountName: contractData?.Account_Info?.accountName || "",
            accountNumber: contractData?.Account_Info?.accountNumber || "",
            accountType: accountTypeName || "",
            bankName: contractData?.Account_Info?.bankName || "",
            bankAddress: contractData?.Account_Info?.bankAddress || "",
            swiftCode: contractData?.Account_Info?.swiftCode || "",
          },
          remarks: contractData.productInfo?.[0]?.remarks || "",
          sellerName: businessName,
          business: {
            address: Business?.address || "",
            tel: Business?.tel || "",
            fax: Business?.fax || "",
          },
          businessLogo: businessLogo,
          supplierSign: supplierSign,
          BuyerSign: buyerSign,
        },
      };
      console.log("EJS template data ", data);
      // Simple EJS template processing
      let processedTemplate = templateContent;

      // Replace logo URL in the template
      processedTemplate = processedTemplate.replace(
        /<img src="[^"]*" alt="PCI Group Logo">/g,
        `<img src="${businessLogo}" alt="${businessName} Logo">`
      );

      // Replace <%= variable %> patterns (escaped HTML)
      processedTemplate = processedTemplate.replace(
        /<%= ?([\w.]+) ?%>/g,
        (match, variable) => {
          // Handle nested properties like "contract.ref"
          const props = variable.split(".");
          let value = data;

          for (const prop of props) {
            value = value?.[prop];
            if (value === undefined) return "[" + variable + "]";
          }

          // Escape HTML for regular variables
          if (typeof value === "string") {
            return value
              .replace(/&/g, "&amp;")
              .replace(/</g, "&lt;")
              .replace(/>/g, "&gt;")
              .replace(/"/g, "&quot;")
              .replace(/'/g, "&#039;");
          }
          return value;
        }
      );

      // Replace <%- variable %> patterns (unescaped HTML)
      processedTemplate = processedTemplate.replace(
        /<%- ?([\w.]+) ?%>/g,
        (match, variable) => {
          // Handle nested properties like "contract.ref"
          const props = variable.split(".");
          let value = data;

          for (const prop of props) {
            value = value?.[prop];
            if (value === undefined) return "[" + variable + "]";
          }

          // Return raw HTML for these variables
          return value || "";
        }
      );

      // Modify the signature sections to hide them when no signatures are available
      const parser = new DOMParser();
      const doc = parser.parseFromString(processedTemplate, "text/html");

      // Get both signature containers
      const buyerSignImg = doc.querySelector(
        ".signature-box:first-child .logo img"
      );
      const sellerSignImg = doc.querySelector(
        ".signature-box:last-child .logo img"
      );
      const buyerSignBox = buyerSignImg?.closest(".logo");
      const sellerSignBox = sellerSignImg?.closest(".logo");
      // Set a consistent height for signatures
      const signatureHeight = "80px";

      // Case 1: Both signatures available - make them the same height
      if (buyerSign && supplierSign) {
        if (buyerSignImg) buyerSignImg.style.height = signatureHeight;
        if (sellerSignImg) sellerSignImg.style.height = signatureHeight;
      }
      // Case 2: Only buyer signature available
      else if (buyerSign && !supplierSign) {
        if (buyerSignImg) buyerSignImg.style.height = signatureHeight;
        if (sellerSignBox) {
          sellerSignBox.innerHTML = ""; // Clear the img
          sellerSignBox.style.height = signatureHeight;
          sellerSignBox.style.display = "block";
        }
      }
      // Case 3: Only seller signature available
      else if (!buyerSign && supplierSign) {
        if (sellerSignImg) sellerSignImg.style.height = signatureHeight;
        if (buyerSignBox) {
          buyerSignBox.innerHTML = ""; // Clear the img
          buyerSignBox.style.height = signatureHeight;
          buyerSignBox.style.display = "block";
        }
      }
      // Case 4: No signatures available - already handled by hiding both

      return doc.documentElement.outerHTML;
    },
    []
  );

  const generatePDF = async () => {
    // Show email confirmation popup ONLY for accounts users, NOT for customer signing
    if (uploadSign) {
      // Customer is signing - directly proceed without showing email confirmation
      handleEmailConfirmation(false);
    } else {
      // Accounts user is approving - show email confirmation popup
      setShowEmailConfirmation(true);
    }
  };

  const handleEmailConfirmation = async (sendEmail) => {
    setShowEmailConfirmation(false);
    setIsGenerating(true);

    try {
      const iframe = document.getElementById("document-preview");
      if (!iframe || !iframe.contentWindow)
        throw new Error("Preview iframe not found");

      // Give the iframe a moment to fully render
      await new Promise((resolve) => setTimeout(resolve, 500));

      const element = iframe.contentWindow.document.body;

      // Direct approach with optimized settings
      const canvas = await html2canvas(element, {
        scale: 2, // Good balance between quality and performance
        useCORS: true,
        logging: false,
        backgroundColor: "#ffffff",
      });

      const imgData = canvas.toDataURL("image/jpeg", 1.0);

      // Create PDF with A4 dimensions (in points)
      const pdf = new jsPDF({
        orientation: "portrait",
        unit: "pt",
        format: "a4",
      });

      // A4 dimensions in points (72 dpi)
      const pageWidth = 595;
      const pageHeight = 842;

      // Add image to fill the entire page with no margins
      pdf.addImage(imgData, "JPEG", 0, 0, pageWidth, pageHeight);

      // Create file
      const fileName = contractDetails?.contractNo || "document";
      // Add suffix to differentiate between initial and signed documents
      const fileNameWithSuffix = uploadSign
        ? `${fileName}_signed`
        : `${fileName}_initial`;
      const fullFileName = fileNameWithSuffix.toLowerCase().endsWith(".pdf")
        ? fileNameWithSuffix
        : `${fileNameWithSuffix}.pdf`;
      const pdfBlob = pdf.output("blob");
      const pdfFile = new File([pdfBlob], fullFileName, {
        type: "application/pdf",
        lastModified: new Date().getTime(),
      });

      // Save locally for immediate feedback
      const link = document.createElement("a");
      link.href = URL.createObjectURL(pdfBlob);
      link.download = fullFileName;
      if (!uploadSign) {
        link.click();
      }

      // Clean up the URL object
      URL.revokeObjectURL(link.href);

      // Also upload to server like Save Upload
      await uploadPDFToServer(pdfFile, sendEmail);
    } catch (error) {
      console.error("Error generating PDF:", error);
      notifyError("Failed to generate PDF: " + error.message);
    } finally {
      setIsGenerating(false);
    }
  };

  const downloadPDF = async () => {
    setIsGenerating(true);
    try {
      const iframe = document.getElementById("document-preview");
      if (!iframe || !iframe.contentWindow)
        throw new Error("Preview iframe not found");

      // Give the iframe a moment to fully render
      await new Promise((resolve) => setTimeout(resolve, 500));

      const element = iframe.contentWindow.document.body;

      // Direct approach with optimized settings
      const canvas = await html2canvas(element, {
        scale: 2, // Good balance between quality and performance
        useCORS: true,
        logging: false,
        backgroundColor: "#ffffff",
      });

      const imgData = canvas.toDataURL("image/jpeg", 1.0);

      // Create PDF with A4 dimensions (in points)
      const pdf = new jsPDF({
        orientation: "portrait",
        unit: "pt",
        format: "a4",
      });

      // A4 dimensions in points (72 dpi)
      const pageWidth = 595;
      const pageHeight = 842;

      // Add image to fill the entire page with no margins
      pdf.addImage(imgData, "JPEG", 0, 0, pageWidth, pageHeight);

      // Create file
      const fileName = contractDetails?.contractNo || "document";
      // Add suffix to differentiate between initial and signed documents
      const fileNameWithSuffix = uploadSign
        ? `${fileName}_signed`
        : `${fileName}_initial`;
      const fullFileName = fileNameWithSuffix.toLowerCase().endsWith(".pdf")
        ? fileNameWithSuffix
        : `${fileNameWithSuffix}.pdf`;
      const pdfBlob = pdf.output("blob");

      // Save locally for immediate feedback
      const link = document.createElement("a");
      link.href = URL.createObjectURL(pdfBlob);
      link.download = fullFileName;
      link.click();

      // Clean up the URL object
      URL.revokeObjectURL(link.href);

      notifySuccess("PDF downloaded successfully!");
    } catch (error) {
      console.error("Error generating PDF:", error);
      notifyError("Failed to generate PDF: " + error.message);
    } finally {
      setIsGenerating(false);
    }
  };

  const uploadPDFToServer = async (pdfFile, sendEmail = false) => {
    try {
      const formData = new FormData();
      formData.append("file", pdfFile);
      if (adminInfo?.id) {
        formData.append("uploadedBy", adminInfo?.id);
      } else {
        formData.append("uploadedBy", contractDetails?.basicInfo?.customer_id);
      }
      if (proformaInvoice) {
        const currentYear = new Date().getFullYear();
        formData.append(
          "file_path",
          `${contractDetails?.productInfo?.[0]?.title}/${currentYear}/Customers/${contractDetails.basicInfo?.buyerCompanyName}/${contractDetails.contractNo}/Proforma Invoice`
        );
      } else {
        const currentYear = new Date().getFullYear();
        formData.append(
          "file_path",
          `${contractDetails?.productInfo?.[0]?.title}/${currentYear}/Customers/${contractDetails.basicInfo?.buyerCompanyName}/${contractDetails.contractNo}/Sales Contracts`
        );
      }
      formData.append("business_id", contractDetails.business);
      formData.append("file_type", "application/pdf");
      formData.append("file_size", pdfFile.size.toString());

      const response = await axios.post(
        `${Base_URL}/documents/uploadDocument`,
        formData,
        {
          headers: { "Content-Type": "multipart/form-data" },
        }
      );

      if (!proformaInvoice) {
        if (response.data.message === "File uploaded successfully") {
          if (response.data.file.s3Key && contractDetails._id) {
            if (uploadSign) {
              await axios.put(
                `${Base_URL}/sales-contracts/update-document-customer/${contractDetails._id}`,
                {
                  template_id: templateId,
                  document_url: response.data.file.s3Key,
                  document_id: response.data.file._id,
                  signature: customer_signature,
                }
              );
            } else {
              await axios.put(
                `${Base_URL}/sales-contracts/add-document-details/${contractDetails._id}`,
                {
                  template_id: templateId.split(":")[0],
                  document_url: response.data.file.s3Key,
                  document_id: response.data.file._id,
                  signature: signatureFileURL,
                }
              );
            }
          }
          setShowPleaseWait(false);

          // Send email if requested
          if (sendEmail && !uploadSign) {
            try {
              await sendContractApprovalEmail(contractDetails);
            } catch (emailError) {
              console.error("Error sending email:", emailError);
              // Don't fail the whole process if email fails
            }
          }

          if (!uploadSign) {
            const successMessage = sendEmail
              ? "Document generated, saved, and sent to customer successfully!"
              : "Document generated and saved successfully!";
            notifySuccess(successMessage);
            onClose();
            if (onSuccess) onSuccess(response.data);
          } else {
            notifySuccess(
              "Document Signed and Contract Accepted successfully!"
            );
          }
        }
      } else {
        if (onSuccess) onSuccess(response.data);
      }
    } catch (error) {
      console.error("Error uploading PDF:", error);
      notifyError("PDF generated but failed to upload: " + error.message);
    } finally {
      setIsGenerating(false);
    }
  };

  const sendContractApprovalEmail = async (contract) => {
    try {
      // Get customer email from contract
      const customerEmail =
        contract?.basicInfo?.selectedCustomerId?.basicInformation
          ?.customerEmail;

      if (!customerEmail) {
        console.warn(
          "No customer email found for contract:",
          contract.contractNo
        );
        return;
      }

      // Call the backend API to send contract approval email
      await axios.post(`${Base_URL}/sales-contracts/send-approval-email`, {
        contractId: contract._id,
        contractNo: contract.contractNo,
        to: customerEmail,
        cc: [], // Can be extended to include CC emails if needed
      });

      console.log(
        "Contract approval email sent successfully to:",
        customerEmail
      );
    } catch (error) {
      console.error("Error sending contract approval email:", error);
      throw error;
    }
  };

  const handlePrint = () => {
    const iframe = document.getElementById("document-preview");
    if (iframe && iframe.contentWindow) {
      iframe.contentWindow.focus();
      iframe.contentWindow.print();
    }
  };

  const handleOpenFilePicker = () => {
    if (fileInputRef.current) fileInputRef.current.click();
  };

  const handleSignedPdfSelected = async (event) => {
    try {
      setIsUploadingSigned(true);
      const file = event.target.files && event.target.files[0];
      if (!file) return;
      if (file.type !== "application/pdf") {
        notifyError("Please select a PDF file");
        return;
      }

      await uploadPDFToServer(file);
      if (onSuccess) onSuccess();
      setSuccessDialogText("File uploaded successfully. Contract accepted.");
      setIsSuccessDialogOpen(true);
    } catch (err) {
      console.error(err);
      notifyError("Failed to upload signed PDF");
    } finally {
      if (fileInputRef.current) fileInputRef.current.value = "";
      setIsUploadingSigned(false);
    }
  };

  const dialogStyle = uploadSign
    ? { maxHeight: "90vh", width: "90%", margin: "0 auto" }
    : { maxHeight: "95vh", height: "95vh", width: "95%", margin: "0 auto" };

  return (
    <Dialog
      open={open}
      onClose={onClose}
      fullWidth
      maxWidth={uploadSign ? "md" : "xl"}
      PaperProps={{
        style: dialogStyle,
      }}
    >
      <DialogTitle className="flex justify-between items-center">
        <Typography variant="h6">
          {templateData?.name || "Document Preview"}
        </Typography>
        <IconButton onClick={onClose} size="small">
          <CloseIcon />
        </IconButton>
      </DialogTitle>

      <DialogContent dividers style={{ padding: 0 }}>
        {isLoading ? (
          <Box className="flex justify-center items-center h-[70vh]">
            <CircularProgress />
          </Box>
        ) : (
          <Box
            className="bg-white rounded-lg overflow-hidden"
            sx={{ height: "100%" }}
          >
            <Grid
              container
              spacing={0}
              sx={{
                m: 0,
                width: "100%",
                height: uploadSign
                  ? "calc(90vh - 160px)"
                  : "calc(95vh - 160px)",
              }}
            >
              {!uploadSign && (
                <Grid
                  item
                  xs={12}
                  md={6}
                  sx={{
                    borderRight: { md: "1px solid #eee" },
                    height: "100%",
                    display: "flex",
                    flexDirection: "column",
                  }}
                >
                  <Box sx={{ p: 2, borderBottom: "1px solid #eee" }}>
                    <Typography variant="h6" color="primary">
                      Initial Contract Documents ({initialDocuments.length})
                    </Typography>
                    {initialDocuments.length > 1 && (
                      <Tabs
                        value={activeTab}
                        onChange={(e, v) => setActiveTab(v)}
                        variant="scrollable"
                        scrollButtons="auto"
                      >
                        {initialDocuments.map((doc, index) => (
                          <Tab
                            key={index}
                            label={doc.name || `Document ${index + 1}`}
                          />
                        ))}
                      </Tabs>
                    )}
                  </Box>
                  <Box sx={{ p: 2, flex: 1, overflow: "hidden" }}>
                    {fetchingInitialDocs ? (
                      <Box className="flex justify-center items-center h-full">
                        <CircularProgress />
                      </Box>
                    ) : selectedInitialDoc ? (
                      <iframe
                        id="initial-doc-viewer"
                        src={`${selectedInitialDoc.url}#toolbar=0`}
                        width="100%"
                        height="100%"
                        style={{ border: "none" }}
                        title="Initial Document"
                      />
                    ) : (
                      <Box className="flex justify-center items-center h-full flex-col">
                        <Typography variant="body2" color="textSecondary">
                          No initial documents
                        </Typography>
                      </Box>
                    )}
                  </Box>
                </Grid>
              )}
              <Grid
                item
                xs={12}
                md={uploadSign ? 12 : 6}
                sx={{
                  height: "100%",
                  display: "flex",
                  flexDirection: "column",
                }}
              >
                <Box
                  className="p-4 bg-gray-100 border-b flex justify-between items-center"
                  sx={{ flexShrink: 0 }}
                >
                  <Typography variant="subtitle1">
                    Contract: {contractDetails?.contractNo || "N/A"}
                  </Typography>
                  <Typography variant="caption" className="text-gray-500">
                    Template: {templateData?.name || "N/A"}
                  </Typography>
                </Box>
                <Box sx={{ flex: 1, overflow: "hidden" }}>
                  <iframe
                    id="document-preview"
                    srcDoc={renderedHtml}
                    style={{ width: "100%", height: "100%", border: 0 }}
                    title="Document Preview"
                  />
                </Box>
              </Grid>
            </Grid>
            <input
              type="file"
              ref={fileInputRef}
              onChange={handleSignedPdfSelected}
              accept="application/pdf"
              style={{ display: "none" }}
            />
          </Box>
        )}
      </DialogContent>

      <DialogActions>
        {uploadSign ? (
          <>
            {!customer_signature && (
              <>
                <Button
                  onClick={handleOpenFilePicker}
                  variant="outlined"
                  startIcon={
                    isUploadingSigned ? (
                      <CircularProgress size={16} />
                    ) : (
                      <Upload />
                    )
                  }
                  disabled={isLoading || isGenerating || isUploadingSigned}
                >
                  {isUploadingSigned
                    ? "Uploading..."
                    : "Upload Signed Document"}
                </Button>
                <Button
                  onClick={downloadPDF}
                  variant="outlined"
                  startIcon={
                    isGenerating ? <CircularProgress size={16} /> : <Download />
                  }
                  disabled={isLoading || isGenerating || isUploadingSigned}
                >
                  Download PDF
                </Button>
                <Button
                  onClick={onUpload}
                  variant="outlined"
                  startIcon={<Print />}
                  disabled={isLoading || isGenerating || isUploadingSigned}
                >
                  Add Signature
                </Button>
              </>
            )}
            {customer_signature && (
              <>
                <Button
                  onClick={() => window.close()}
                  variant="outlined"
                  startIcon={<CloseIcon />}
                >
                  Close
                </Button>
                <Button
                  onClick={downloadPDF}
                  variant="outlined"
                  startIcon={
                    isGenerating ? <CircularProgress size={16} /> : <Download />
                  }
                  disabled={isLoading || isGenerating || isUploadingSigned}
                >
                  Download PDF
                </Button>
              </>
            )}
          </>
        ) : (
          <>
            <Button
              onClick={handlePrint}
              variant="outlined"
              startIcon={<Print />}
              disabled={isLoading || isGenerating || isUploadingSigned}
            >
              Print
            </Button>
            <Button
              onClick={() => setRejectOpen(true)}
              color="error"
              variant="outlined"
            >
              Reject
            </Button>
            <Button
              onClick={() => setAmendOpen(true)}
              color="warning"
              variant="outlined"
            >
              Request Amendment
            </Button>
            <Button
              onClick={generatePDF}
              variant="contained"
              color="primary"
              disabled={isLoading || isGenerating || isUploadingSigned}
              startIcon={
                isGenerating ? <CircularProgress size={16} /> : <Download />
              }
            >
              {isGenerating ? "Approving..." : "Approve"}
            </Button>
          </>
        )}
      </DialogActions>

      {/* Please Wait Popup */}
      <Dialog open={showPleaseWait} onClose={() => {}} maxWidth="xs" fullWidth>
        <DialogTitle>Please Wait</DialogTitle>
        <DialogContent>
          <Box className="flex flex-col items-center justify-center py-4">
            <CircularProgress size={40} className="mb-4" />
            <Typography variant="body1" className="text-center">
              Accepting Contract...
            </Typography>
            <Typography
              variant="body2"
              className="text-center text-gray-600 mt-2"
            >
              This may take a few moments
            </Typography>
          </Box>
        </DialogContent>
      </Dialog>

      {/* Reject Dialog (Sales) */}
      <Dialog
        open={rejectOpen}
        onClose={() => !isRejecting && setRejectOpen(false)}
        maxWidth="sm"
        fullWidth
      >
        <DialogTitle>Reject Contract</DialogTitle>
        <DialogContent>
          <Typography variant="body2" className="mb-2">
            Please provide a reason:
          </Typography>
          <textarea
            className="w-full border rounded-md p-2"
            rows={4}
            value={rejectReason}
            onChange={(e) => setRejectReason(e.target.value)}
            placeholder="Reason for rejection..."
            disabled={isRejecting}
          />
        </DialogContent>
        <DialogActions>
          <Button
            onClick={() => setRejectOpen(false)}
            variant="outlined"
            disabled={isRejecting}
          >
            Cancel
          </Button>
          <Button
            color="error"
            variant="contained"
            disabled={isRejecting || !rejectReason.trim()}
            startIcon={
              isRejecting ? (
                <CircularProgress size={16} color="inherit" />
              ) : null
            }
            onClick={async () => {
              if (!rejectReason.trim()) return;
              setIsRejecting(true);
              try {
                await axios.put(
                  `${Base_URL}/sales-contracts/status/${contractDetails?._id}`,
                  { status: "Rejected (Accounts)", reason: rejectReason }
                );
                notifySuccess("Contract rejected", () => {
                  setRejectOpen(false);
                  onClose();
                  window.location.reload();
                });
              } catch (err) {
                notifyError("Failed to reject");
                setIsRejecting(false);
              }
            }}
          >
            {isRejecting ? "Rejecting..." : "Confirm Reject"}
          </Button>
        </DialogActions>
      </Dialog>

      {/* Request Amendment Dialog (Sales) */}
      <Dialog
        open={amendOpen}
        onClose={() => !isRequestingAmendment && setAmendOpen(false)}
        maxWidth="sm"
        fullWidth
      >
        <DialogTitle>Request Amendment</DialogTitle>
        <DialogContent>
          <Typography variant="body2" className="mb-2">
            Please provide details:
          </Typography>
          <textarea
            className="w-full border rounded-md p-2"
            rows={4}
            value={amendComment}
            onChange={(e) => setAmendComment(e.target.value)}
            placeholder="What needs to be changed and why..."
            disabled={isRequestingAmendment}
          />
        </DialogContent>
        <DialogActions>
          <Button
            onClick={() => setAmendOpen(false)}
            variant="outlined"
            disabled={isRequestingAmendment}
          >
            Cancel
          </Button>
          <Button
            color="warning"
            variant="contained"
            disabled={isRequestingAmendment || !amendComment.trim()}
            startIcon={
              isRequestingAmendment ? (
                <CircularProgress size={16} color="inherit" />
              ) : null
            }
            onClick={async () => {
              if (!amendComment.trim()) return;
              setIsRequestingAmendment(true);
              try {
                await axios.put(
                  `${Base_URL}/sales-contracts/status/${contractDetails?._id}`,
                  {
                    status: "Amendments Requested (Accounts)",
                    comment: amendComment,
                  }
                );
                notifySuccess("Amendment requested (to Sales)", () => {
                  setAmendOpen(false);
                  onClose();
                  window.location.reload();
                });
              } catch (err) {
                notifyError("Failed to request amendment");
                setIsRequestingAmendment(false);
              }
            }}
          >
            {isRequestingAmendment ? "Requesting..." : "Send Request"}
          </Button>
        </DialogActions>
      </Dialog>

      {/* Success Confirmation Dialog */}
      <Dialog
        open={isSuccessDialogOpen}
        onClose={handleSuccessOk}
        maxWidth="xs"
        fullWidth
      >
        <DialogTitle>Success</DialogTitle>
        <DialogContent>
          <Typography variant="body2">
            {successDialogText ||
              "File uploaded successfully. Contract accepted."}
          </Typography>
        </DialogContent>
        <DialogActions>
          <Button onClick={handleSuccessOk} variant="contained" color="primary">
            OK
          </Button>
        </DialogActions>
      </Dialog>

      {/* Email Confirmation Modal */}
      <EmailConfirmationModal
        open={showEmailConfirmation}
        onClose={() => setShowEmailConfirmation(false)}
        onConfirm={handleEmailConfirmation}
        contractNo={contractDetails?.contractNo || "N/A"}
        customerName={
          contractDetails?.basicInfo?.finalCustomerName ||
          contractDetails?.basicInfo?.buyerCompanyName ||
          "Customer"
        }
        isProcessing={isGenerating}
      />
    </Dialog>
  );
};

export default DocumentGenerator;
